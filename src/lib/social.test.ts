import { describe, expect, it } from 'vitest'
import {
  needsSetup,
  describeNotification,
  hasLeft,
  looksAutoGenerated,
  rankLabel,
  rankWithTies,
  sameChallengePeople,
  whoLabel,
  workoutMinutes,
  type AppNotification,
  type Challenge,
} from './social'

const chal = (over: Partial<Challenge>): Challenge => ({
  id: 'c',
  creator: 'a',
  members: ['a', 'b'],
  accepted: ['a', 'b'],
  declined: [],
  metric: 'workouts',
  title: 't',
  startDay: '2026-01-01',
  endDay: '2026-01-07',
  createdAt: '',
  scores: {},
  ...over,
})

describe('rankWithTies', () => {
  it('shares ranks for equal scores', () => {
    const r = rankWithTies([5, 5, 3, 1])
    expect(r.map(rankLabel)).toEqual(['T1', 'T1', '3', '4'])
  })
  it('does not mark a lone leader as tied', () => {
    expect(rankWithTies([4, 2]).map(rankLabel)).toEqual(['1', '2'])
  })
})

describe('looksAutoGenerated', () => {
  it('flags suggested handles', () => {
    expect(looksAutoGenerated('claytonbanks482')).toBe(true)
    expect(looksAutoGenerated('qajakeppl1025545')).toBe(true)
    expect(looksAutoGenerated('jake')).toBe(false)
    expect(looksAutoGenerated('jake_7')).toBe(false)
  })
})

describe('challenge people', () => {
  it('ignores people who declined or left', () => {
    expect(sameChallengePeople(chal({}), ['a', 'b'])).toBe(true)
    expect(sameChallengePeople(chal({ members: ['a', 'b', 'c'], declined: ['c'] }), ['a', 'b'])).toBe(true)
    expect(sameChallengePeople(chal({}), ['a', 'c'])).toBe(false)
  })
  it('detects leavers', () => {
    expect(hasLeft(chal({ declined: ['b'] }), 'b')).toBe(true)
    expect(hasLeft(chal({ accepted: ['a'], declined: ['b'] }), 'b')).toBe(false)
  })
})

describe('names', () => {
  it('leads with the display name', () => {
    expect(whoLabel({ username: 'jake', displayName: 'Jake QA' })).toBe('Jake QA')
    expect(whoLabel({ username: 'jake', displayName: '' })).toBe('@jake')
    expect(whoLabel(undefined, 'old')).toBe('@old')
  })
  it('describes a request by name with the handle on the side', () => {
    const n = { id: '1', type: 'friend_request', from: 'u', fromUsername: 'jake', createdAt: '', read: false } as AppNotification
    const d = describeNotification(n, { username: 'jake', displayName: 'Jake QA' })
    expect(d.title).toBe('Jake QA sent you a friend request')
    expect(d.handle).toBe('@jake')
  })
})

describe('minutes', () => {
  it('uses session length', () => {
    expect(workoutMinutes({ durationSec: 1830 })).toBe(31)
  })
})

describe('needsSetup', () => {
  const base = { uid: 'u', username: 'abc', displayName: '' }
  it('is true for a new profile still on its first handle', () => {
    expect(needsSetup({ ...base, freeChange: true, joinedAt: '2026-10-24T10:00:00.000Z', usernameChangedAt: '2026-10-24T10:00:00.000Z' })).toBe(true)
  })
  it('is false for a rename granted later, so only the rename button unlocks', () => {
    expect(needsSetup({ ...base, freeChange: true, joinedAt: '2026-10-01T10:00:00.000Z', usernameChangedAt: '2026-10-24T10:00:00.000Z' })).toBe(false)
  })
  it('is false once the free change is spent or there is no profile', () => {
    expect(needsSetup({ ...base, freeChange: false, joinedAt: 'x', usernameChangedAt: 'x' })).toBe(false)
    expect(needsSetup(undefined)).toBe(false)
  })
})
